import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const pdfFile = process.argv[2];
if (!pdfFile) {
  console.error('Usage: node scripts/build-horror-pages.mjs <file.pdf>');
  process.exit(1);
}

const root = process.cwd();
const extractor = path.join(root, 'scripts', 'extract-pdf-text.mjs');
const outputFile = path.join(root, 'app', 'lib', 'horrorPages.generated.js');
const extracted = execFileSync(process.execPath, [extractor, pdfFile], {
  encoding: 'utf8',
  maxBuffer: 10 * 1024 * 1024,
});

const chapters = [
  [1, 'Kendaraan Berhantu', 'Melyanda Ulan Dari'],
  [6, 'Rumah Terkutuk', 'Ummi Khurnia Farti'],
  [12, 'Gubuk Hijau', 'Ummi Al Hasanah'],
  [22, 'Rumah Tua Misterius', 'Nadila Putri Aprianty'],
  [28, 'Kontrakan Berhantu', 'Deka Mardatillah'],
  [39, 'Mitos di Balik Malam Satu Suro', 'Resma Azizah Yatasya'],
  [44, 'Rumah Seram Berakhir Menimbulkan Kenangan Terindah', 'Cecilia Alfaris'],
  [47, 'Bau Menyengat Pertanda Kedatangannya', 'Ario Tandayu'],
  [54, 'Keluarga', 'Deri Aprinato'],
  [58, 'Pengganggu pada Saat Pengabdian', 'Ryan Topani'],
];

function cleanPage(chunk, pageNumber) {
  const lines = chunk
    .replaceAll('\u0000', '')
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean);

  lines.shift();
  const openingChapter = chapters.find(([start]) => start === pageNumber);
  if (openingChapter) {
    const authorIndex = lines.findIndex((line) => /^Oleh\s*:/i.test(line));
    if (authorIndex >= 0) {
      const authorOnSameLine = lines[authorIndex].replace(/^Oleh\s*:\s*/i, '').trim();
      lines.splice(0, authorIndex + (authorOnSameLine ? 1 : 2));
    }
  }

  const cleaned = [];
  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index];
    if (line === '⃝꙰⃝' || /^[~•○]+$/.test(line)) continue;

    if (line === '-' && cleaned.length && lines[index + 1]) {
      const previous = cleaned.pop();
      const next = lines[index + 1];
      const previousWord = previous.match(/([A-Za-z]+)$/)?.[1] || '';
      const nextWord = next.match(/^([A-Za-z]+)/)?.[1] || '';
      const keepHyphen = previousWord.toLowerCase() === nextWord.toLowerCase() || previousWord.length === 1;
      cleaned.push(`${previous}${keepHyphen ? '-' : ''}${next}`);
      index += 1;
      continue;
    }

    cleaned.push(line);
  }

  const text = cleaned
    .join(' ')
    .replace(/\s+([,.;:!?])/g, '$1')
    .replace(/([(“„])\s+/g, '$1')
    .replace(/\s+([)”])/g, '$1')
    .replace(/\s{2,}/g, ' ')
    .trim();

  const paragraphs = [];
  let remaining = text;
  while (remaining.length > 720) {
    const candidates = [...remaining.slice(360, 760).matchAll(/[.!?”](?=\s+[A-Z“"])/g)];
    const splitAt = candidates.length ? 360 + candidates.at(-1).index + 1 : 700;
    paragraphs.push(remaining.slice(0, splitAt).trim());
    remaining = remaining.slice(splitAt).trim();
  }
  if (remaining) paragraphs.push(remaining);
  return paragraphs.join('\n\n');
}

const numberedPages = new Map();
for (const chunk of extracted.split(/\n\n---PAGE---\n\n/)) {
  const pageNumber = Number.parseInt(chunk.trim().split(/\r?\n/, 1)[0], 10);
  if (pageNumber >= 1 && pageNumber <= 60 && !numberedPages.has(pageNumber)) {
    numberedPages.set(pageNumber, cleanPage(chunk, pageNumber));
  }
}

if (numberedPages.size !== 60) {
  throw new Error(`Expected 60 story pages, found ${numberedPages.size}.`);
}

const pages = [...numberedPages].map(([pageNumber, content]) => {
  const chapterIndex = chapters.findLastIndex(([start]) => start <= pageNumber);
  const [chapterStart, chapterTitle, chapterAuthor] = chapters[chapterIndex];
  const part = pageNumber - chapterStart + 1;
  return {
    page_number: pageNumber,
    page_title: part === 1 ? chapterTitle : `${chapterTitle} - Bagian ${part}`,
    chapter_title: chapterTitle,
    chapter_author: chapterAuthor,
    is_chapter_start: part === 1,
    content,
  };
});

const source = `// Generated from the supplied book PDF by scripts/build-horror-pages.mjs.\n` +
  `// Do not edit this file manually; regenerate it when the source book changes.\n` +
  `const horrorPages = ${JSON.stringify(pages, null, 2)};\n\nexport default horrorPages;\n`;

fs.writeFileSync(outputFile, source, 'utf8');
console.log(`Generated ${pages.length} native reader pages in ${path.relative(root, outputFile)}.`);
